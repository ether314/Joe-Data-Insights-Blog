export function serviceCoveragePct(row: StateSalesTaxRow): number {
  return (100 * row.servicesTaxed) / FTA_SURVEY_TOTAL_SERVICES;
}

/** Reliance × narrowness: high when sales-tax dependent and few services taxed. */
export function exposureScore(row: StateSalesTaxRow): number | null {
  if (!row.hasGst || row.salesTaxShareOfCollectionsPct == null) return null;
  const narrowness = 1 - row.servicesTaxed / FTA_SURVEY_TOTAL_SERVICES;
  return Math.round(10 * row.salesTaxShareOfCollectionsPct * narrowness) / 10;
}

