export type StateTradeRow = {
  state: string;
  abbr: string;
  region: Region;
  trade: TradeId;
  /** OEWS employment */
  employment: number;
  /** Desk FY new RAP entrants in this trade */
  newEntrants: number;
  /** Projected annual retirements (desk) */
  retirements: number;
  /** newEntrants / retirements */
  entrantsPerRetirement: number;
  /** Completers proxy ≈ entrants × 0.55 (cancellation + lag) */
  completersProxy: number;
  confidence: Confidence;
  note: string;
};

const ELEC_55 = 0.184;
const PLUMB_55 = 0.204;
const COHORT_YEARS = 10;

function retirements(employment: number, share55: number): number {
  return Math.round((employment * share55) / COHORT_YEARS);
}

function ratio(entrants: number, ret: number): number {
  if (ret <= 0) return 0;
  return Math.round((entrants / ret) * 100) / 100;
}

